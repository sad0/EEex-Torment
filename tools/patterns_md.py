# Generate PATTERNS.md from gen_report.json (+ manual.json notes).
import json, collections, re
from ilib import REPO

G = json.load(open('gen_report.json'))
M = json.load(open('manual.json'))

METHOD_DOC = [
    ('curdb', 'db', 'upstream BG pattern already matched uniquely in Torment and was confirmed by other evidence'),
    ('vote', 'vote', 'masked instruction-window voting (port2.py) + context scoring (decide.py)'),
    ('fmap', 'fmap', 'global function map BG->PT (signatures, call-graph propagation, link order) (globalmap*.py)'),
    ('align', 'align', 'instruction alignment inside the mapped function (final.py)'),
    ('local', 'local', 'anchors on neighbouring mapped calls / caller votes inside the mapped function (local.py)'),
    ('gxref', 'gxref', 'data target voted over all BG RIP-relative references (gxref.py)'),
    ('manual', 'manual', 'hand review of BG/PT disassembly (manual.json, show.py/rv.py)'),
]


def short_method(m):
    m = m.replace(' (db pattern kept)', '')
    if m.startswith('manual'):
        return 'manual'
    if m.startswith('local'):
        return 'local'
    if m.startswith('gxref'):
        return 'gxref'
    if m.startswith('fmap(callee)'):
        return 'fmap (callee)'
    parts = sorted({p.split(':')[0] for p in m.split('+')})
    return '+'.join(('db' if p == 'curdb' else p) for p in parts if p)


def cat(n):
    if n.startswith('Hardcoded_'):
        return 'Loader (Hardcoded_*)'
    if re.match(r'(lua|luaL|luaopen|tolua)_?', n):
        return 'Lua API'
    if n.startswith('Hook-'):
        return 'Hooks'
    if n.startswith('Data-'):
        return 'Data / return pointers'
    if n.endswith('::VFTable'):
        return 'VFTables'
    return 'Engine functions & globals'


rows = collections.defaultdict(list)
cnt = collections.Counter(); conf = collections.Counter()
for n, r in sorted(G.items()):
    st = r['status']
    cnt[st] += 1
    note = r.get('note') or ''
    if n in M and M[n].get('note'):
        note = M[n]['note']
    note = note.replace('|', '/').replace('\n', ' ').strip(' -')
    if st == 'ported':
        conf[r['conf']] += 1
        meth = short_method(r['method'])
        rows[cat(n)].append(f"| `{n}` | ported | {meth} | {r['conf']} | {r['addr']} | {note} |")
    else:
        rows[cat(n)].append(f"| `{n}` | {st} | {short_method(r.get('method', '-'))} | - | - | {note} |")

phase5 = [n for n, v in M.items() if re.search(r'phase 5|must|adapt', v.get('note', ''))]

out = []
out.append('# EEex pattern port: BG2EE v2.6.6.0 -> Torment.exe v3.2.2.0\n')
out.append('Generated by `tools/patterns_md.py` from `tools/gen_report.json` and `tools/manual.json`.\n')
out.append(f"**{cnt['ported']} ported, {cnt['unsupported']} unsupported, {cnt['unresolved']} unresolved** "
           f"(confidence of ported: {conf['high']} high, {conf['medium']} medium, {conf['low']} low). "
           'The full `poc/InfinityLoader.db` loads in-game: 0 "Could not find", 821 addresses cached by the loader, POC `EEex_Main.lua` prints.\n')
out.append('## Methods\n')
out.append('| method | meaning |\n|---|---|')
for k, s, d in METHOD_DOC:
    out.append(f'| {s} | {d} |')
out.append('\nConfidence: **high** = two independent methods agree or exact code match; **medium** = one strong method, '
           'or reviewed by hand with PST-specific code differences; **low** = best available guess, revisit in phase 4/5.\n')
out.append('Scope: every entry was located and its surrounding code compared (normalized instructions, call targets, '
           'data references). Hook *bodies* (registers, stack offsets, restore sizes) were not re-validated one by one: '
           'PTEE often uses other registers and struct offsets (e.g. CDerivedStats +8, CGameSprite fields shifted), so each '
           'EEex hook must be checked when the Lua patches are ported (phase 5); known cases are listed below.\n')
out.append('Addresses are RVAs in Torment.exe v3.2.2.0 (image base 0x140000000). For rel32 entries the address is the final target.\n')
out.append('## Unsupported (tolerated by the loader; EEex Lua must guard these labels)\n')
for n, r in sorted(G.items()):
    if r['status'] == 'unsupported':
        out.append(f"- `{n}`: {(M.get(n, {}).get('note') or r.get('note') or '').strip()}")
out.append('\n## Phase 5 follow-ups (hook bodies / semantics differ in PTEE)\n')
for n in sorted(phase5):
    out.append(f"- `{n}`: {M[n]['note']}")
for c in ['Loader (Hardcoded_*)', 'Lua API', 'Engine functions & globals', 'VFTables', 'Data / return pointers', 'Hooks']:
    out.append(f'\n## {c}\n')
    out.append('| name | status | method | confidence | PT address | notes |\n|---|---|---|---|---|---|')
    out += rows[c]
open(REPO + r'\PATTERNS.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(cnt, conf, len(phase5), 'phase5 notes')
