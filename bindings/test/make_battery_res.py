# Dev-only resources for PSTEE_Battery.lua (opcode extension tests), written to bindings/test/dev_override/
# (copied to the dev game's override by eeexlua/build.py --deploy), plus PSTEE_BatterySpells.lua. Never shipped.
#   python bindings/test/make_battery_res.py
import os, struct
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'dev_override')
GAME = r'E:\Enhanced Edition\Environnement de test\PSTEE (EEex dev)'
NUL, CRLF, TAB = b'\x00', '\r\n', '\t'


def res8(s):
    return s.encode('latin-1').ljust(8, NUL)[:8]


def eff(opcode, param1=0, param2=0, res='', duration=0, timing=0, special=0, param3=0, target=2, power=0, save=0):
    """EFF V2.0, 0x110 bytes (IESDP): opcode 0x10, target 0x14, power 0x18, param1 0x1c, param2 0x20, timing 0x24,
    duration 0x28, probability 0x2c/0x2e, resource 0x30, saving throw 0x40, special 0x48, param3 0x5c."""
    b = bytearray(0x110)
    b[0:16] = b'EFF V2.0EFF V2.0'
    struct.pack_into('<IIIiIII', b, 0x10, opcode, target, power, param1, param2, timing, duration)
    struct.pack_into('<HH', b, 0x2c, 100, 0)
    b[0x30:0x38] = res8(res)
    struct.pack_into('<I', b, 0x40, save)
    struct.pack_into('<I', b, 0x48, special)
    struct.pack_into('<i', b, 0x5c, param3)
    return bytes(b)


def spl(features):
    """SPL V1 with one ability (target 1 creature, projectile 1 none) holding `features`
    [(opcode, param1, param2, res)], each permanent on the preset target."""
    hdr = bytearray(0x72)
    hdr[0:8] = b'SPL V1  '
    struct.pack_into('<ii', hdr, 0x08, -1, -1)
    struct.pack_into('<H', hdr, 0x1c, 1)          # wizard
    struct.pack_into('<I', hdr, 0x34, 1)          # level 1
    struct.pack_into('<ii', hdr, 0x50, -1, -1)
    struct.pack_into('<IHI', hdr, 0x64, 0x72, 1, 0x72 + 0x28)
    struct.pack_into('<HH', hdr, 0x6e, 0, 0)
    ab = bytearray(0x28)
    ab[0] = 1                                     # spell form: standard
    struct.pack_into('<H', ab, 0x02, 4)           # location: spell
    ab[0x0c] = 1                                  # target: living actor
    ab[0x0d] = 1
    struct.pack_into('<H', ab, 0x0e, 30)
    struct.pack_into('<H', ab, 0x10, 1)
    struct.pack_into('<HH', ab, 0x1e, len(features), 0)
    struct.pack_into('<H', ab, 0x26, 1)           # projectile: none
    fe = b''
    for opcode, p1, p2, r in features:
        f = bytearray(0x30)
        struct.pack_into('<HBBiiBB', f, 0, opcode, 2, 0, p1, p2, 1, 0)   # target preset, timing 1 permanent
        f[0x12] = 100
        f[0x14:0x1c] = res8(r)
        fe += bytes(f)
    return bytes(hdr) + bytes(ab) + fe


def spl_names(game):
    k = open(os.path.join(game, 'chitin.key'), 'rb').read()
    nb, nr, ob, orr = struct.unpack_from('<IIII', k, 8)
    out = set()
    for i in range(nr):
        name, typ, loc = struct.unpack_from('<8sHI', k, orr + 14 * i)
        n = name.rstrip(NUL).decode('latin-1').upper()
        # player spells only (mage, priest, innate): the other SPL are plot / cutscene scripts
        if typ == 0x3ee and n[:4] in ('SPWI', 'SPPR', 'SPIN'):
            out.add(n)
    return sorted(out)


def main():
    os.makedirs(OUT, exist_ok=True)
    files = {
        # op248 / op249 hit effect: InvokeLua PTEEB248 on the creature hit
        'PTEEB248.EFF': eff(402, res='PTEEB248'),
        # op219 protection from creature type (param2 2 = EA.IDS, param1 255 = ENEMY), bonus 5 from param3
        'PTEEB219.EFF': eff(219, param1=255, param2=2, param3=5, timing=0, duration=60),
        # op333 static charge: 2 charges of PTEEB333.SPL (InvokeLua), save checked once (param3 bit 0)
        'PTEEB333.EFF': eff(333, param1=2, param2=1, res='PTEEB333', timing=0, duration=12, param3=1),
        # op326 payload (op326 param2 102 = SPLPROT row EA, value from param1): InvokeLua PTEEB326
        'PTEEB326.SPL': spl([(402, 0, 0, 'PTEEB326')]),
        'PTEEB333.SPL': spl([(402, 0, 0, 'PTEEB333')]),
    }
    # per-frame tick for the battery runner
    menu = ['menu', '{', TAB + 'name "PSTEE_Battery_Menu"', TAB + 'ignoreesc', TAB + 'label', TAB + '{',
            TAB * 2 + 'area 0 0 1 1', TAB * 2 + 'enabled "PSTEE_Battery_Tick()"', TAB + '}', '}']
    files['PTEEBAT.menu'] = (CRLF.join(menu) + CRLF).encode('latin-1')
    for name, data in files.items():
        open(os.path.join(OUT, name), 'wb').write(data)
        print(name, len(data))
    # every SPL of the game, for PSTEE_Battery.lua's spells-apply step
    names = spl_names(GAME)
    lua = ['-- generated by make_battery_res.py: every player SPL (SPWI / SPPR / SPIN) in chitin.key', 'PSTEE_BAT_ALL_SPELLS = {']
    lua += [TAB + '"' + n + '",' for n in names] + ['}']
    open(os.path.join(HERE, 'PSTEE_BatterySpells.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lua) + '\n')
    print('PSTEE_BatterySpells.lua', len(names))


if __name__ == '__main__':
    main()
