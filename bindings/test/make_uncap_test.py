# Build bindings/test/PSTEE_UncapTest.lua from upstream EEex_UncapFPS_Patch.lua with the three Torment
# instruction-layout differences (tools: hook sites compared BG/PT):
#  - CScreenWorld::OnEvent middle-mouse jump is a short je in Torment: restore the next instruction (7 bytes)
#  - CInfinity screen-shake post jump is a near jne in Torment (BG short + 3 restored bytes): restore nothing
#  - CGameArea::OnActivation's last call is a call (BG tail jmp): hook after the call, pArea in rdi
import os
HERE = os.path.dirname(os.path.abspath(__file__))
s = open(os.path.join(HERE, r'..\..\ref\EEex\EEex\copy\EEex_scripts\EEex_UncapFPS_Patch.lua'), encoding='utf-8').read()


def rep(old, new):
    global s
    assert s.count(old) == 1, old
    s = s.replace(old, new)


rep('EEex_HookConditionalJumpOnFailWithLabels(EEex_Label("Hook-CScreenWorld::OnEvent()-OnHandleMiddleMouseDragJmp"), 0, {',
    'EEex_HookConditionalJumpOnFailWithLabels(EEex_Label("Hook-CScreenWorld::OnEvent()-OnHandleMiddleMouseDragJmp"), 7, { -- EEex-PSTEE: short je')
rep('EEex_HookConditionalJumpOnFailWithLabels(EEex_Label("Hook-CInfinity::Render()-HandleScreenShakePostJmp"), 3, {',
    'EEex_HookConditionalJumpOnFailWithLabels(EEex_Label("Hook-CInfinity::Render()-HandleScreenShakePostJmp"), 0, { -- EEex-PSTEE: near jne')
i = s.index('	EEex_HookRelativeJumpWithLabels(EEex_Label("Hook-CGameArea::OnActivation()-LastCall"), {')
j = s.index('	)\n', i) + 3
s = s[:i] + '''	-- EEex-PSTEE: Torment calls the map engine (no tail jump) and keeps pArea in rdi
	EEex_HookAfterCallWithLabels(EEex_Label("Hook-CGameArea::OnActivation()-LastCall"), {
		{"hook_integrity_watchdog_ignore_registers", {
			EEex_HookIntegrityWatchdogRegister.RAX, EEex_HookIntegrityWatchdogRegister.RCX, EEex_HookIntegrityWatchdogRegister.RDX,
			EEex_HookIntegrityWatchdogRegister.R8, EEex_HookIntegrityWatchdogRegister.R9, EEex_HookIntegrityWatchdogRegister.R10,
			EEex_HookIntegrityWatchdogRegister.R11
		}}},
		{[[
			mov rcx, rdi ; pArea
			call #L(EEex::UncapFPS_Hook_OnAfterAreaActivated)
		]]}
	)
''' + s[j:]
head = '''-- EEex-PSTEE phase 4d test (generated by make_uncap_test.py): EEex's Uncap FPS patch (EEex_UncapFPS_Patch.lua,
-- upstream v1.3.1) with Torment's hook-site layouts; option defaults of EEex_UncapFPS.lua; the Lua-side
-- keyboard scrolling is phase 5 (stubbed).
function EEex_UncapFPS_LuaHook_CheckKeyboardScroll() end
function EEex_UncapFPS_LuaHook_OnAfterDrawInit() end
function EEex_Menu_LuaHook_OnWindowSizeChanged() end
'''
tail = '''
EEex.UncapFPS_FPSLimitEnabled = false
EEex.UncapFPS_FPSLimit = EEex.GetHighestRefreshRate()
EEex.UncapFPS_BusyWaitThreshold = 1
EEex.UncapFPS_FullscreenVRR = false
EEex.SetUncapFPSEnabled(true)
print("PSTEE-TEST: Uncap FPS installed and enabled")
'''
open(os.path.join(HERE, 'PSTEE_UncapTest.lua'), 'w', encoding='utf-8', newline='\n').write(head + s + tail)
print('PSTEE_UncapTest.lua written')
